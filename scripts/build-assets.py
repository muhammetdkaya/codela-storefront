"""Join critical theme assets without changing CSS/JS semantics or requiring npm.

Sources remain the editable source of truth. Commit generated files, and run
--check in CI/packaging so a source edit can never ship an outdated bundle.
"""
import argparse
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[1] / "theme/codela-storefront/assets"
BUNDLES = {
    "styles/storefront-base.css": (
        "styles/tokens.css", "storefront.css", "styles/overlay.css",
        "styles/navigation.css", "styles/components.css",
    ),
    "styles/document-navigation.css": (
        "styles/document-continuity.css", "styles/navigation-feedback.css",
        "styles/commerce-skeleton.css",
    ),
    "scripts/document-navigation.js": (
        "scripts/navigation-feedback.js", "scripts/document-continuity.js",
    ),
}


def render(target, sources):
    parts = ["/* Generated by scripts/build-assets.py; edit the listed sources. */\n"]
    for name in sources:
        source = (ROOT / name).read_text(encoding="utf-8")
        if target.endswith(".css"):
            if re.search(r"@(import|charset)\b", source):
                raise ValueError(f"{name}: imports/charsets cannot be concatenated")
            # Files in styles/ retain their relative icon URLs. The root-level
            # storefront.css currently has none; fail if this contract changes.
            if Path(name).parent != Path(target).parent:
                for url in re.findall(r"url\(\s*['\"]?([^'\"\s)]+)", source):
                    if not re.match(r"(?:[a-z][a-z0-9+.-]*:|/|#)", url, re.I):
                        raise ValueError(f"{name}: rebase relative URL before bundling: {url}")
        parts.append(f"\n/* Source: {name} */\n{source.rstrip()}\n")
        if target.endswith(".js"):
            parts.append(";\n")
    return "".join(parts).encode("utf-8")


def build(check=False):
    # Validate checked-in dependencies even when packaging without Node.
    runpy.run_path(str(Path(__file__).with_name('check-vendor.py')))['check']()
    stale = []
    for target, sources in BUNDLES.items():
        expected = render(target, sources)
        output = ROOT / target
        if check:
            if not output.is_file() or output.read_bytes() != expected:
                stale.append(target)
        else:
            output.write_bytes(expected)
    if stale:
        raise ValueError("Stale theme assets; run python3 scripts/build-assets.py: " + ", ".join(stale))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
