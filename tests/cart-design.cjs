// Mobile cart UI contract: native Woo Store API and shared UI Kit remain authoritative.
const assert=require('node:assert/strict'),fs=require('node:fs');
const dir='theme/codela-storefront/';
const js=fs.readFileSync(dir+'assets/scripts/cart-controller.js','utf8');
const css=fs.readFileSync(dir+'assets/styles/overlay.css','utf8');
const html=fs.readFileSync(dir+'inc/render.php','utf8');
const icon=fs.readFileSync(dir+'assets/icons/trash-2.svg','utf8');
assert(js.includes("t('Items in cart: %d')"),'Localized item count');
assert(js.includes('sf-stepper sf-ui-surface'),'Native glass quantity');
assert(js.includes('sf-remove sf-ui-icon-button sf-ui-icon-button--clear'),'Removal retains existing UI Kit icon button');
assert(js.includes('sf-remove-icon" aria-hidden="true"'),'Decorative removal icon');
assert(js.includes("escape(t('Remove'))"),'Accessible label');
assert(js.includes("'/remove-item'")&&js.includes("'/update-item'"),'Woo API mutations');
assert(css.includes('#sf-panel.is-cart-panel:not(.is-product-cart) #sf-panel-title'),'Heading hidden visually');
assert(css.includes('min-height:var(--sf-overlay-toolbar-height);padding:10px var(--sf-overlay-gutter)'),'Cart close aligns with search 68px toolbar');
assert(css.includes('border-bottom:0;justify-content:flex-end'),'Close remains right-aligned');
assert(css.includes('.sf-cart-count + .sf-cart-row{padding-top:0}'),'First row keeps compact top spacing');
assert(css.includes('-webkit-line-clamp:2'),'Two-row item title');
assert(css.includes('aspect-ratio:1'),'Square photos');
assert(css.includes('gap:12px;align-items:start;padding:12px 0'),'Compact mobile rows');
assert(css.includes('height:30px;min-height:30px;overflow:visible'),'Visible quantity pill is actually 30px tall, not 44px');
assert(css.includes('width:44px;height:44px;min-height:44px'),'Quantity buttons retain 44px touch targets despite smaller pill');
assert(css.includes('min-width:14px;padding:0;font-size:13px'),'Quantity capsule is slimmer');
assert(css.includes('.sf-stepper .sf-cart-quantity-current'),'Stepper text styles do not reach the spinner');
assert(css.includes('.sf-cart-busy>.sf-ui-spinner') && css.includes('width:16px;height:16px;min-width:0;min-height:0'),'Spinner is explicitly square');
assert(css.includes('--sf-state-mark-size:52px') && css.includes('--sf-state-mark-gap:12px') && css.includes('width:var(--sf-state-mark-size);height:var(--sf-state-mark-size)'),'Empty cart uses shared 52px icon and 12px spacing');
assert(css.includes('--sf-state-heading-size:19px') && css.includes('--sf-state-heading-weight:500') && css.includes('font-size:var(--sf-state-heading-size);font-weight:var(--sf-state-heading-weight)'),'Cart and account use one heading scale');
assert(css.includes('min-width:44px;min-height:44px'),'Remove retains minimum touch target');
assert(css.includes('width:32px;height:32px'),'Glass removal visual is smaller than its touch target');
assert(css.includes('rgba(255,255,255,.55)'),'Quantity glass material is less dominant');
assert(css.includes("mask:url('../icons/trash-2.svg')"),'Shared licensed icon');
assert(icon.includes('xmlns="http://www.w3.org/2000/svg"'),'Icon is SVG');
assert(icon.includes('width="56" height="56" viewBox="0 0 56 56"'),'Filled deletion glyph matches existing icon geometry');
assert(html.includes('aria-labelledby="sf-panel-title"'),'Accessible native dialog');
assert(!js.includes("t('Continue shopping')"),'No empty-state CTA');
console.log('Mobile cart layout contract: passed');
