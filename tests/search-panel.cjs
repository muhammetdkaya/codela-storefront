// Runtime search-control checks. No fake product data; skeleton is shown only while fetching.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const js = fs.readFileSync('theme/codela-storefront/assets/storefront.js','utf8');
const css = ['assets/storefront.css','assets/styles/overlay.css'].map(p=>fs.readFileSync('theme/codela-storefront/'+p,'utf8')).join('\n');
const markup = fs.readFileSync('theme/codela-storefront/inc/render.php','utf8');
const start = js.indexOf('function syncSearchControls() {');
const end = js.indexOf('\nasync function search() {', start);
assert.ok(start > 0 && end > start, 'Search state synchronizer must exist');
const input = {value:''};
const clear = {hidden:false};
const elements = {'#sf-query':input,'.sf-search-clear':clear};
const run = () => vm.runInNewContext(js.slice(start,end) + '\nsyncSearchControls();', {$:selector=>elements[selector]});
run();
assert.equal(clear.hidden,true,'Empty search hides clear button');
input.value='x';run();
assert.equal(clear.hidden,false,'Typing shows clear button');
input.value=' ayakkabı ';run();
assert.equal(clear.hidden,false,'Search field remains clearable for real user queries');
input.value='';run();
assert.equal(clear.hidden,true,'Clearing hides button again');
assert.ok(!markup.includes('sf-search-suggestion'),'No duplicate typed-query suggestion below input');
assert.ok(!js.includes('sf-search-suggestion'),'Removed suggestion listener');
assert.ok(!css.includes('sf-search-suggestion'),'Removed suggestion styles');
assert.ok(!js.includes("t('Continue shopping')"),'Empty cart does not show redundant continue shopping CTA');
assert.ok(js.includes("t('Your cart is empty.')"),'Empty cart message remains');
assert.ok(js.includes('row.repeat(6)'), 'Six static skeleton rows while a real query is in flight');
assert.ok(js.includes("if (sequence !== searchSequence || current !== 'search') return;"),'Stale results must not overwrite new searches');
assert.ok(!js.includes('placePanelReveal') && !js.includes('PANEL_MOTION_MS'), 'Fullscreen reveal animation removed');
assert.ok(css.includes('transition:none!important'), 'Panels open and close without transition');
assert.ok(css.includes('--sf-overlay-control-size:44px'), 'All overlay X controls share a 44px touch target');
assert.ok(css.includes('--sf-overlay-toolbar-height:68px'), 'All panel headers share the same height');
assert.ok(css.includes('#sf-panel .sf-panel-top{'), 'Menu and cart have a shared toolbar');
assert.ok(css.includes('#sf-panel.is-search-panel .sf-search-toolbar{'), 'Search uses matching toolbar tokens');
assert.ok(css.includes('height:46px'), 'Search field is reduced from 52px to 46px');
assert.ok(fs.readFileSync('theme/codela-storefront/assets/styles/tokens.css','utf8').includes('--sf-ui-icon-close:19px'), 'X glyph token is 19px');
assert.ok(css.includes('background:#ffffff'), 'Panel backgrounds are white');
assert.ok(css.includes('color-scheme:light'), 'Search uses light input/color controls');
assert.ok(!css.includes('background:#0b0d12'), 'Dark search background must be removed');
assert.ok(css.includes('#sf-panel.is-search-panel .sf-panel-top{display:none!important}'),'Only the inline X appears in search');
assert.ok(markup.includes("placeholder=\"<?php esc_attr_e( 'Search', 'codela-storefront' ); ?>\""),'Search placeholder is Ara in Turkish');
console.log('Search clear control, no duplicate query and no empty-cart CTA: passed.');
